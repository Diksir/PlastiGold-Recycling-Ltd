function normalizeStory(story = {}) {
  const about = { ...defaultContent.story.about, ...(story.about || {}) };
  const video = {
    ...defaultContent.story.video,
    ...(story.video || {}),
  };

  if (!video.videoUrl) {
    video.videoUrl = defaultContent.story.video.videoUrl;
  }

  if (!video.poster || video.poster === '/assets/recycling-plant.svg') {
    video.poster = defaultContent.story.video.poster;
  }

  return { about, video };
}

function normalizeServices(value) {
  return arrayOrDefault(value, defaultContent.services).map((service) => {
    const upgrade = serviceImageUpgrades[String(service.name || '').trim().toLowerCase()];
    if (!upgrade) return service;
    return { ...service, ...upgrade };
  });
}

function normalizeImpactStats(value) {
  return arrayOrDefault(value, defaultContent.impactStats).map((stat) => {
    if (String(stat.label || '').trim().toLowerCase() !== 'tons of plastic recycled') return stat;
    return { ...stat, value: '10,000+' };
  });
}

export function mergeContent(data = {}) {
  return {
    ...defaultContent,
    ...data,
    hero: { ...defaultContent.hero, ...(data.hero || {}) },
    navItems: arrayOrDefault(data.navItems, defaultContent.navItems),
    heroFeatures: arrayOrDefault(data.heroFeatures, defaultContent.heroFeatures),
    slides: arrayOrDefault(data.slides, defaultContent.slides),
    sections: { ...defaultContent.sections, ...(data.sections || {}) },
    impactStats: normalizeImpactStats(data.impactStats),
    services: normalizeServices(data.services),
    processSteps: arrayOrDefault(data.processSteps, defaultContent.processSteps),
    whyCards: arrayOrDefault(data.whyCards, defaultContent.whyCards),
    gallery: arrayOrDefault(data.gallery, defaultContent.gallery),
    testimonials: arrayOrDefault(data.testimonials, defaultContent.testimonials),
    story: normalizeStory(data.story),
    cta: { ...defaultContent.cta, ...(data.cta || {}) },
    contact: { ...defaultContent.contact, ...(data.contact || {}) },
    footer: {
      ...defaultContent.footer,
      ...(data.footer || {}),
      socialLinks: {
        ...defaultContent.footer.socialLinks,
        ...(data.footer?.socialLinks || {}),
      },
    },
  };
}

export function mapQueryFromContact(contact = defaultContent.contact) {
  const nextContact = { ...defaultContent.contact, ...contact };
  if (nextContact.latitude && nextContact.longitude) {
    return `${nextContact.latitude},${nextContact.longitude}`;
  }
  return nextContact.address || nextContact.city || defaultContent.contact.address;
}

export function googleMapsUrlForContact(contact = defaultContent.contact) {
  return `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(mapQueryFromContact(contact))}`;
}

export function googleMapsEmbedForContact(contact = defaultContent.contact) {
  return `https://www.google.com/maps?q=${encodeURIComponent(mapQueryFromContact(contact))}&z=16&output=embed`;
}

export function whatsappUrlForContact(contact = defaultContent.contact) {
  const number = String(contact.whatsapp || contact.phone || '').replace(/\D/g, '');
  return `https://wa.me/${number || defaultContent.contact.whatsapp}`;
}
